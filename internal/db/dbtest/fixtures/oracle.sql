CREATE OR REPLACE PACKAGE shop AS
  FUNCTION total(cid NUMBER) RETURN NUMBER;
END shop;
/

CREATE OR REPLACE PACKAGE BODY shop AS
  FUNCTION total(cid NUMBER) RETURN NUMBER IS
    t NUMBER;
  BEGIN
    SELECT COALESCE(SUM(amount), 0) INTO t FROM orders WHERE customer_id = cid;
    RETURN t;
  END;
END shop;
