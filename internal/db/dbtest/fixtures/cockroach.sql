DROP SCHEMA IF EXISTS lumino_test CASCADE;
CREATE SCHEMA lumino_test;

CREATE TABLE lumino_test.customers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    email varchar(200) UNIQUE,
    created_at timestamp DEFAULT now()
);
COMMENT ON TABLE lumino_test.customers IS 'People who buy things';

CREATE TABLE lumino_test.orders (
    id serial PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES lumino_test.customers (id) ON DELETE CASCADE,
    amount numeric(10,2) NOT NULL DEFAULT 0,
    status varchar(20) NOT NULL CHECK (status IN ('new', 'paid', 'shipped')),
    note text
);
CREATE INDEX orders_status_idx ON lumino_test.orders (status);

CREATE TABLE lumino_test.order_items (
    order_id integer NOT NULL REFERENCES lumino_test.orders (id) ON DELETE CASCADE,
    line_no integer NOT NULL,
    sku varchar(40) NOT NULL,
    qty integer NOT NULL DEFAULT 1,
    PRIMARY KEY (order_id, line_no)
);

CREATE TABLE lumino_test.all_types (
    id integer PRIMARY KEY,
    c_int integer,
    c_bigint bigint,
    c_dec numeric(12,4),
    c_float double precision,
    c_bool boolean,
    c_text text,
    c_varchar varchar(50),
    c_date date,
    c_time time,
    c_ts timestamp(6),
    c_tstz timestamptz,
    c_bytes bytea,
    c_json jsonb,
    c_uuid uuid,
    c_arr integer[],
    c_interval interval
);
