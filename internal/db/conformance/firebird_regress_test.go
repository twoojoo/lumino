func fbRegressConn(t *testing.T) (db.Conn, db.Session) {
	t.Helper()
	tg := dbtest.Targets()["firebird"]
	if !dbtest.Reachable("127.0.0.1:55050") {
		t.Skip("firebird not reachable (make db-up)")
	}
	ctx := context.Background()
	cfg := tg.Config
	conn, err := db.Open(ctx, &cfg, db.OpenOptions{})
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	t.Cleanup(func() { conn.Close() })
	s, err := conn.Session(ctx)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { s.Close() })
	return conn, s
}

func fbExec(t *testing.T, s db.Session, q string) {
	t.Helper()
	res, err := s.Execute(context.Background(), q)
	if err != nil {
		t.Fatalf("%s: %v", q, err)
	}
	res.Close()
}

func TestFirebirdRegressExecuteBlockReturns(t *testing.T) {
	_, s := fbRegressConn(t)
	ctx := context.Background()
	cols, rows, err := dbtest.Query(ctx, s, `EXECUTE BLOCK RETURNS (x INTEGER, s VARCHAR(10)) AS
DECLARE v INTEGER = 1;
BEGIN
  x = v; s = 'a'; SUSPEND;
  x = 2; s = 'b'; SUSPEND;
END`)
	if err != nil {
		t.Fatal(err)
	}
	if len(cols) != 2 || len(rows) != 2 || rows[1][0] != int64(2) || rows[1][1] != "b" {
		t.Fatalf("EXECUTE BLOCK RETURNS lost its result: cols=%v rows=%v", cols, rows)
	}
	// input parameters before RETURNS, and a block without output
	_, rows, err = dbtest.Query(ctx, s, "EXECUTE BLOCK (a INTEGER = ?) RETURNS (y INTEGER) AS BEGIN y = a * 2; SUSPEND; END", 5)
	if err != nil || len(rows) != 1 || rows[0][0] != int64(10) {
		t.Fatalf("EXECUTE BLOCK with inputs: %v %v", rows, err)
	}
	res, err := s.Execute(ctx, "EXECUTE BLOCK AS DECLARE r INTEGER; BEGIN r = 1; END")
	if err != nil {
		t.Fatal(err)
	}
	if res.Columns() != nil {
		t.Fatalf("EXECUTE BLOCK without RETURNS has columns %v", res.Columns())
	}
	res.Close()
}

func TestFirebirdRegressTextAndBinary(t *testing.T) {
	_, s := fbRegressConn(t)
	cols, rows, err := dbtest.Query(context.Background(), s, `SELECT CAST('ab  ' AS VARCHAR(10)) AS vc, CAST('ab' AS CHAR(5)) AS c,
  CAST(x'00ff10' AS VARBINARY(4)) AS vb, CAST(x'c3' AS VARCHAR(4) CHARACTER SET OCTETS) AS oct,
  CAST('héllo' AS VARCHAR(10)) AS u
FROM RDB$DATABASE`)
	if err != nil {
		t.Fatal(err)
	}
	r := rows[0]
	if r[0] != "ab  " {
		t.Errorf("VARCHAR trailing spaces stripped: %q", r[0])
	}
	if r[1] != "ab" {
		t.Errorf("CHAR padding kept: %q", r[1])
	}
	if b, ok := r[2].([]byte); !ok || !bytes.Equal(b, []byte{0, 0xff, 0x10}) {
		t.Errorf("VARBINARY value %#v (%s)", r[2], cols[2].DBType)
	}
	if b, ok := r[3].([]byte); !ok || !bytes.Equal(b, []byte{0xc3}) {
		t.Errorf("OCTETS value %#v", r[3])
	}
	if r[4] != "héllo" {
		t.Errorf("UTF8 text %q", r[4])
	}
}

func TestFirebirdRegressDSNEscaping(t *testing.T) {
	fbRegressConn(t)
	ctx := context.Background()
	for _, name := range []string{"/var/lib/firebird/data/lumino.fdb#x", "/var/lib/firebird/data/lumino.fdb?x", "/var/lib/firebird/data/lumino%2Efdb"} {
		cfg := dbtest.Targets()["firebird"].Config
		cfg.Database = name
		conn, err := db.Open(ctx, &cfg, db.OpenOptions{})
		if err == nil {
			conn.Close()
			t.Errorf("%q opened another database", name)
		}
	}
	// credentials with URL characters reach the server intact (wrong
	// password: the error must be an authentication one, not a DSN one)
	cfg := dbtest.Targets()["firebird"].Config
	cfg.Password = "p@ss:w/rd#?%"
	if conn, err := db.Open(ctx, &cfg, db.OpenOptions{}); err == nil {
		conn.Close()
		t.Fatal("wrong password accepted")
	} else if !strings.Contains(strings.ToLower(err.Error()), "password") {
		t.Errorf("unexpected error for a wrong password: %v", err)
	}
}

func TestFirebirdRegressIPv6Host(t *testing.T) {
	cfg := dbtest.Targets()["firebird"].Config
	cfg.Host = "::1" // nothing listens there: the dial must fail, not the address parsing
	conn, err := db.Open(context.Background(), &cfg, db.OpenOptions{})
	if err == nil {
		conn.Close()
		return
	}
	if msg := err.Error(); strings.Contains(msg, "too many colons") || strings.Contains(msg, "missing port") || !strings.Contains(msg, "[::1]:55050") {
		t.Fatalf("IPv6 address not bracketed: %v", err)
	}
}

func TestFirebirdRegressIdentityDDL(t *testing.T) {
	conn, s := fbRegressConn(t)
	ctx := context.Background()
	drop := func() {
		if res, err := s.Execute(ctx, "DROP TABLE LUMINO_REG_IDENT"); err == nil {
			res.Close()
		}
	}
	drop()
	t.Cleanup(drop)
	fbExec(t, s, `CREATE TABLE LUMINO_REG_IDENT (
  A INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 5) NOT NULL,
  B INTEGER GENERATED BY DEFAULT AS IDENTITY,
  C INTEGER)`)
	ddl, err := conn.Catalog().DDL(ctx, db.ObjectRef{Name: "LUMINO_REG_IDENT", Type: db.ObjTable})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`A INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 5)`, `B INTEGER GENERATED BY DEFAULT AS IDENTITY`} {
		if !strings.Contains(ddl, want) {
			t.Errorf("DDL lacks %q:\n%s", want, ddl)
		}
	}
	if strings.Count(ddl, "IDENTITY") != 2 {
		t.Errorf("DDL identities:\n%s", ddl)
	}
	// the DDL recreates the same table
	drop()
	if err := dbtest.Load(ctx, conn, ddl); err != nil {
		t.Fatalf("DDL round trip: %v\n%s", err, ddl)
	}
	fbExec(t, s, "INSERT INTO LUMINO_REG_IDENT (C) VALUES (1)")
	_, rows, err := dbtest.Query(ctx, s, "SELECT A FROM LUMINO_REG_IDENT")
	if err != nil || len(rows) != 1 || rows[0][0] != int64(100) {
		t.Fatalf("identity start: %v %v", rows, err)
	}
}
