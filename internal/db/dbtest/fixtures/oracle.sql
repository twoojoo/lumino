CREATE TABLE customers (
    id NUMBER(10) NOT NULL PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(200) UNIQUE,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);
COMMENT ON TABLE customers IS 'People who buy things';

CREATE TABLE orders (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER(10) NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    amount NUMBER(10,2) DEFAULT 0 NOT NULL,
    status VARCHAR2(20) NOT NULL CHECK (status IN ('new', 'paid', 'shipped')),
    note CLOB
);
CREATE INDEX orders_status_idx ON orders (status);

CREATE TABLE order_items (
    order_id NUMBER(10) NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_no NUMBER(10) NOT NULL,
    sku VARCHAR2(40) NOT NULL,
    qty NUMBER(10) DEFAULT 1 NOT NULL,
    PRIMARY KEY (order_id, line_no)
);

